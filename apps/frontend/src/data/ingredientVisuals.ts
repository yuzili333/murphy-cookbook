const normalizeIngredientName = (value: string) => value.replace(/\s+/g, '').toLowerCase();

export function getIngredientVisual(name: string) {
  const normalized = normalizeIngredientName(name);
  const exactMatch = ingredientVisuals.find((item) =>
    [item.name, ...(item.aliases ?? [])].some((candidate) => normalized === normalizeIngredientName(candidate)),
  );

  if (exactMatch) {
    return exactMatch;
  }

  return (
    ingredientVisuals.find((item) =>
      [item.name, ...(item.aliases ?? [])].some((candidate) => {
        const normalizedCandidate = normalizeIngredientName(candidate);
        return normalized.includes(normalizedCandidate) || normalizedCandidate.includes(normalized);
      }),
    ) ?? defaultIngredientVisual
  );
}
